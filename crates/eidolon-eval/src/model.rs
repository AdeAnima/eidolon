//! Versioned, independent deserialization types for ground truth and CLI reports.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};

/// Version-one corpus manifest; paths in files and pairs are relative to `root`.
#[derive(Debug, Deserialize, Serialize)]
pub struct Truth {
    /// Schema version.
    pub version: u32,
    /// Deterministic generator seed.
    pub seed: u64,
    /// Canonical corpus directory.
    pub root: PathBuf,
    /// Requested corpus size.
    pub scale: String,
    /// Local source provenance, retained for reproducibility.
    pub sources: Vec<Source>,
    /// Complete set of generated media files.
    pub files: Vec<TruthFile>,
    /// Duplicate edges and visibility/registration-qualified version relationships.
    pub pairs: Vec<ExpectedPair>,
    /// Negative direct predictions; unrelated source pairs also forbid group connectivity.
    pub hard_negatives: Vec<PathPair>,
}

/// Local source bytes and their origin.
#[derive(Debug, Deserialize, Serialize)]
pub struct Source {
    /// Original local pathname or command description.
    pub origin: String,
    /// Retained source file, relative to corpus root.
    pub retained: PathBuf,
    /// SHA-256 of the retained bytes.
    pub sha256: String,
}

/// One generated file with its transformation category.
#[derive(Debug, Deserialize, Serialize)]
pub struct TruthFile {
    /// Relative media pathname.
    pub path: PathBuf,
    /// `image`, `video`, or `text`.
    pub kind: String,
    /// Transformation category, or `original`.
    pub variant: String,
    /// Duplicate lineage; unannotated siblings in one lineage are excluded from precision.
    pub family: String,
    /// Shared source-design hypothesis; unproven cross-source pairs remain unscored.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub design: Option<String>,
    /// SHA-256 of the generated bytes.
    pub sha256: String,
    /// Scene coordinates used to align deliberately different image windows.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub scene: Option<SceneWindow>,
}

/// Pixel coordinates in a retained source scene, before JPEG encoding or resizing.
#[derive(Clone, Debug, Deserialize, Serialize)]
pub struct SceneWindow {
    /// Shared retained scene identity.
    pub source: String,
    /// Left edge in source pixels.
    pub x: u32,
    /// Top edge in source pixels.
    pub y: u32,
    /// Window width in source pixels.
    pub width: u32,
    /// Window height in source pixels.
    pub height: u32,
}

/// A path pair without a relation label.
#[derive(Debug, Deserialize, Serialize)]
pub struct PathPair {
    /// First relative pathname.
    pub a: PathBuf,
    /// Second relative pathname.
    pub b: PathBuf,
    /// Whether only direct predictions are negative; shared-source group connectivity is allowed.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub direct_only: bool,
}

/// Expected relationship: containment always orders part before whole.
#[derive(Debug, Deserialize, Serialize)]
pub struct ExpectedPair {
    /// Part for directional relations; otherwise either endpoint.
    pub a: PathBuf,
    /// Whole for directional relations; otherwise either endpoint.
    pub b: PathBuf,
    /// Core-compatible snake-case relation label.
    pub relation: String,
    /// Media family used for category metrics.
    pub kind: String,
    /// Transformation used for category metrics.
    pub variant: String,
    /// Measured aligned RGB change (0–255) for strong versions and subtle duplicate colors.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub visible_rgb_mae: Option<f64>,
    /// Additional labels accepted for equivalent duplicate interpretations (e.g. canvas padding).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub accepted_relations: Vec<String>,
}

/// The subset of CLI JSON consumed by the evaluator.
#[derive(Debug, Deserialize)]
pub struct Output {
    /// CLI schema version.
    pub version: u32,
    /// ID-to-path mapping; IDs need not be contiguous.
    pub files: Vec<OutputFile>,
    /// Direct detector or exact-stage matches.
    pub matches: Vec<OutputMatch>,
    /// Reported connected groups.
    pub groups: Vec<OutputGroup>,
}

/// CLI file identity.
#[derive(Debug, Deserialize)]
pub struct OutputFile {
    /// Bare numeric core file ID.
    pub id: usize,
    /// Absolute pathname, or path relative to the corpus root.
    pub path: PathBuf,
    /// Original remote media identity when `path` is a fetched local artifact.
    #[serde(default)]
    pub url: Option<UrlOrigin>,
}

/// Provenance shared with the CLI's URL-backed file reports.
#[derive(Debug, Deserialize)]
pub struct UrlOrigin {
    /// Original media URL.
    pub url: String,
    /// Counted response-body bytes, including probes.
    #[serde(default)]
    pub bytes_fetched: u64,
    /// Complete media size when known.
    pub total_size: Option<u64>,
}

/// One direct reported relation.
#[derive(Debug, Deserialize)]
pub struct OutputMatch {
    /// Part for containment.
    pub a: usize,
    /// Whole for containment.
    pub b: usize,
    /// Core-compatible relation label.
    pub relation: String,
    /// Detector confidence, used to select among repeated pair reports.
    pub score: f64,
}

/// CLI connected component.
#[derive(Debug, Deserialize)]
pub struct OutputGroup {
    /// Member IDs; `keep_hint` and other fields are intentionally ignored.
    pub files: Vec<usize>,
}
